// fetch-resume-data.mjs
// Build-time "database connection": pulls the resume repo
// (HOS-Qian-jia-hong-resume) raw files and embeds them into src/data/.
// The blog renders this content directly — edit the resume repo, rebuild, done.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(__dirname, "..", "src", "data");
const REPO = "lxcxjxhx/HOS-Qian-jia-hong-resume";
const BRANCH = "main";
const FILES = ["README.md", "PR/README.md"];

async function fetchRaw(file, tries = 4) {
  const url = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/${file}`;
  let lastErr;
  for (let i = 1; i <= tries; i++) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(30000) });
      if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
      return await res.text();
    } catch (e) {
      lastErr = e;
      console.warn(`attempt ${i}/${tries} failed for ${file}: ${e.message}`);
      await new Promise((r) => setTimeout(r, 1500 * i));
    }
  }
  throw lastErr;
}

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const stamp = new Date().toISOString();
  for (const file of FILES) {
    const text = await fetchRaw(file);
    const name = file.replace(/\//g, "_").replace(/\.md$/, "").toLowerCase();
    const header =
      `// Auto-generated by scripts/fetch-resume-data.mjs — do not edit.\n` +
      `// Source: https://github.com/${REPO} (${file}) @ ${stamp}\n`;
    const body = `export const source = ${JSON.stringify({ file, fetchedAt: stamp })};\nexport const markdown = \`${esc(text)}\`;\n`;
    const out = path.join(OUT_DIR, `${name}.ts`);
    fs.writeFileSync(out, header + body, "utf-8");
    console.log(`fetched ${file} (${text.length} chars) -> src/data/${name}.ts`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
